#!/usr/bin/env python3
"""
gen_daec.py - generates the RTL, the golden test vectors and the hand metrics for the SEC-DED-DAEC (39,32) code
of Dutta and Touba (VTS 2007), from the golden model model/daec.py.

Files written (do not edit):
    rtl/ecc/daec_pkg.sv             H columns, row masks, adjacent-pair syndromes + accessor functions
    rtl/ecc/daec_enc_flat.sv        check-bit network, flat XOR per row
    rtl/ecc/daec_enc_cse.sv         check-bit network, common sub-expression elimination
    rtl/ecc/daec_enc_tree.sv        check-bit network, balanced 2-input XOR tree per row
    rtl/ecc/daec_corr_cmp.sv        correction logic: 39 single + 38 adjacent-pair syndrome comparators
    tb/vectors/daec_vectors.hex     54,204 golden vectors (same plan as the Hsiao vectors)
    reports/daec_hand_metrics.md    XOR counts, depth, comparator literals

Hand-written (static) files that use them: rtl/ecc/daec_enc.sv, daec_dec.sv, daec_ooc_wrap.sv.

Vector layout (168 bits = 42 hex digits, same as the Hsiao vectors, bit 2 is new):
    [166:128] error mask   [127:89] cw_in = codeword XOR mask   [88:57] data_out   [56:18] cw_out
    [17:11] syndrome   [10] ce (single corrected)   [9] ue   [8:3] err_pos (lowest corrected bit)   [2] ae (adjacent pair corrected)
The original codeword is recovered as cw_in XOR mask.

Run:  python3 model/gen_daec.py
"""
import os, sys
from itertools import combinations

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import hsiao
import daec
import gen as G

N, K, R = daec.N, daec.K, daec.R
H = daec.H
ADJ = daec.ADJ
DROWS = [[j for j in range(K) if (H[j] >> i) & 1] for i in range(R)]      # data bits in parity row i

HDR = "// GENERATED by model/gen_daec.py from model/daec.py - DO NOT EDIT\n`timescale 1ns / 1ps\n"

def gen_pkg():
    cols = ", ".join("7'b%s" % format(H[j], "07b") for j in reversed(range(N)))
    masks = ", ".join("32'h%08X" % sum(1 << b for b in DROWS[i]) for i in reversed(range(R)))
    t = HDR + """// SEC-DED-DAEC (39,32) constants, H-matrix of Dutta and Touba (VTS 2007), Fig. 2.
// Codeword: cw[31:0] = data, cw[38:32] = check bits.  dh_col(j)[i] = 1: bit j is in parity row i.
package daec_pkg;
    localparam int DATA_W = 32;
    localparam int CHK_W  = 7;
    localparam int CW_W   = 39;

    // Column j of H occupies H_COL_FLAT[7*j +: 7]  (listed j = 38 ... 0)
    localparam logic [CW_W*CHK_W-1:0] H_COL_FLAT = {
        %s
    };

    // Data bits feeding check bit i: ROW_MASK_FLAT[32*i +: 32]  (listed i = 6 ... 0)
    localparam logic [CHK_W*DATA_W-1:0] ROW_MASK_FLAT = {
        %s
    };

    function automatic logic [CHK_W-1:0] dh_col(input int j);
        return H_COL_FLAT[CHK_W*j +: CHK_W];
    endfunction

    // syndrome of the double adjacent error in bits i and i+1 (i = 0 ... 37)
    function automatic logic [CHK_W-1:0] dadj_col(input int i);
        return dh_col(i) ^ dh_col(i + 1);
    endfunction

    function automatic logic [DATA_W-1:0] drow_mask(input int i);
        return ROW_MASK_FLAT[DATA_W*i +: DATA_W];
    endfunction
endpackage
""" % (cols, masks)
    G.wpath("rtl/ecc/daec_pkg.sv", t)

def gen_encoders():
    G.ROWS = DROWS                       # the encoder builders of gen.py read the rows from this global
    G.HDR = HDR
    out = []
    for name, impl, desc, fn in (("daec_enc_flat", 1, "flat XOR expression per row", G.enc_flat),
                                 ("daec_enc_cse", 2, "common sub-expression elimination", G.enc_cse),
                                 ("daec_enc_tree", 3, "balanced 2-input XOR tree per row", G.enc_tree)):
        lines, nets, xors, depth = fn()
        G.emit_enc(name, impl, desc, lines, nets, xors, depth)
        out.append((impl, desc, xors, depth))
    return out

def gen_corr():
    body = []
    for j in range(N): body.append("    assign flip_s[%d] = (syn == 7'b%s);" % (j, format(H[j], "07b")))
    for i in range(N - 1): body.append("    assign flip_a[%d] = (syn == 7'b%s);" % (i, format(ADJ[i], "07b")))
    for j in range(N):
        terms = ["flip_s[%d]" % j]
        if j < N - 1: terms.append("flip_a[%d]" % j)
        if j > 0: terms.append("flip_a[%d]" % (j - 1))
        body.append("    assign flip[%d] = %s;" % (j, " | ".join(terms)))
    t = HDR + """// Correction logic of the SEC-DED-DAEC code (paper, section 6, Fig. 5).
//   flip_s[j] = syndrome equals column j            (single error in bit j)
//   flip_a[i] = syndrome equals column i XOR i+1    (double adjacent error in bits i and i+1)
//   flip[j]   = bit j has to be inverted = flip_s[j] | flip_a[j] | flip_a[j-1]
//   ce        = a single error was found            ae = an adjacent double error was found
module daec_corr_cmp (
    input  logic  [6:0] syn,
    output logic [38:0] flip,
    output logic        ce,
    output logic        ae
);
    logic [38:0] flip_s;
    logic [37:0] flip_a;
%s
    assign ce = |flip_s;
    assign ae = |flip_a;
endmodule
""" % "\n".join(body)
    G.wpath("rtl/ecc/daec_corr_cmp.sv", t)
    return 7 * N + 7 * (N - 1)          # literals: 39 + 38 seven-input comparators

def gen_vectors():
    vec = []
    def add(orig, mask):
        cw = orig ^ mask
        d, co, s, kind, fl = daec.decode(cw)
        ce = 1 if kind == "single" else 0
        ae = 1 if kind == "adjacent" else 0
        ue = 1 if kind == "ue" else 0
        pos = fl[0] if fl else 0
        v = ((mask << 128) | (cw << 89) | (d << 57) | (co << 18) | (s << 11)
             | (ce << 10) | (ue << 9) | (pos << 3) | (ae << 2))
        vec.append("%042x" % v)
    for d in hsiao.test_words(10):
        cw = daec.encode(d)
        add(cw, 0)
        for j in range(N): add(cw, 1 << j)
        for a, b in combinations(range(N), 2): add(cw, (1 << a) | (1 << b))
    for d in (0x00000000, 0x89ABCDEF):
        cw = daec.encode(d)
        for a, b, c in combinations(range(N), 3): add(cw, (1 << a) | (1 << b) | (1 << c))
    G.wpath("tb/vectors/daec_vectors.hex", "\n".join(vec) + "\n")
    return len(vec)

def main():
    print("P12 SEC-DED-DAEC generator")
    daec.self_test()
    p = daec.properties()
    assert p["forbidden 4-cycles (4FC)"] == 0 and p["total 4-cycles"] == 1363 and p["bad 4-cycles (4BC)"] == 379
    gen_pkg()
    enc = gen_encoders()
    lits = gen_corr()
    nvec = gen_vectors()
    hs = G.__dict__  # noqa
    md = ["# Hand metrics of the SEC-DED-DAEC code (generated by model/gen_daec.py)", "",
          "Syndrome = encoder network on the received data, XOR the received check bits (+1 XOR level).", "",
          "| Encoder IMPL | Structure | 2-input XORs | Logic depth |", "| --- | --- | --- | --- |",
          "| 0 | behavioural reduction (synthesis decides) | %d before sharing | - |" % sum(len(r) - 1 for r in DROWS)]
    for impl, desc, x, dpt in enc: md.append("| %d | %s | %d | %d |" % (impl, desc, x, dpt))
    md += ["", "| Correction logic | Seven-input comparators | Literals | Notes |", "| --- | --- | --- | --- |",
           "| Hsiao, comparators (ecc_corr_cmp) | 39 | 273 | ce = OR of the 39 flips |",
           "| SEC-DED-DAEC, comparators (daec_corr_cmp) | 39 + 38 | %d | flip[j] = single(j) or adjacent(j-1,j) or adjacent(j,j+1) |" % lits, "",
           "Paper (Table 1): syndrome generator 96 two-input XORs, depth 4 - the same as the Hsiao code; the extra cost is in the corrector.",
           "Test vectors: %d (46 data words x (1 clean + 39 single + 741 double) + 2 x 9139 triples)." % nvec]
    G.wpath("reports/daec_hand_metrics.md", "\n".join(md) + "\n")
    print("\n".join(md))

if __name__ == "__main__":
    main()
