#!/usr/bin/env python3
"""
gen.py - generates every derived artefact of the P12 SEC-DED codec from hsiao.py.

    python3 model/gen.py                    (run from the project root; needs pyeda)
    python3 model/gen.py --vectors-only     (only tb/vectors/ecc_vectors.hex; no pyeda needed)

Writes
  rtl/ecc/ecc_pkg.sv            H columns and row masks
  rtl/ecc/ecc_enc_flat.sv       IMPL 1: one XOR expression per check bit
  rtl/ecc/ecc_enc_cse.sv        IMPL 2: common sub-expression elimination
  rtl/ecc/ecc_enc_tree.sv       IMPL 3: balanced 2-input XOR tree per check bit
  rtl/ecc/ecc_corr_cmp.sv       correction by 39 syndrome comparators (dec IMPL 1, 2)
  rtl/ecc/ecc_corr_espresso.sv  correction from ESPRESSO-minimised logic (dec IMPL 3)
  model/decoder.pla             ESPRESSO input (Berkeley PLA, type fdr)
  model/decoder_min.pla         ESPRESSO result
  tb/vectors/ecc_vectors.hex    test vectors for tb_ecc_codec (42 hex digits per line, see gen_vectors)
  reports/ecc_hand_metrics.md   XOR count / logic depth per variant
Every generated file starts with a "GENERATED - do not edit" header.
"""
import os, sys, random
from itertools import combinations

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import hsiao
from hsiao import H, K, R, N, encode, decode, syndrome, inject, row_bits, test_words

HDR = "// GENERATED by model/gen.py from model/hsiao.py - DO NOT EDIT\n`timescale 1ns / 1ps\n"
KEEP = ("`ifndef ECC_KEEP_ATTR\n"
        "  `ifdef ECC_KEEP\n    `define ECC_KEEP_ATTR (* keep = \"true\" *)\n"
        "  `else\n    `define ECC_KEEP_ATTR\n  `endif\n`endif\n")

def wpath(rel, text):
    p = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w") as f:
        f.write(text)
    print("  wrote", rel)

ROWS = row_bits()

# ============================================================== package
def gen_pkg():
    cols = ", ".join("7'b%s" % format(H[j], "07b") for j in reversed(range(N)))
    masks = ", ".join("32'h%08X" % sum(1 << b for b in ROWS[i]) for i in reversed(range(R)))
    t = HDR + """// Hsiao (39,32) SEC-DED constants.
// Codeword: cw[31:0] = data, cw[38:32] = check bits.  h_col(j)[i] = 1: bit j is in parity row i.
package ecc_pkg;
    localparam int DATA_W = 32;
    localparam int CHK_W  = 7;
    localparam int CW_W   = 39;

    // Column j of H occupies H_COL_FLAT[7*j +: 7]  (listed j = 38 ... 0)
    localparam logic [CW_W*CHK_W-1:0] H_COL_FLAT = {
        %s
    };

    // Data bits feeding check bit i: ROW_MASK_FLAT[32*i +: 32]  (listed i = 6 ... 0)
    localparam logic [CHK_W*DATA_W-1:0] ROW_MASK_FLAT = {
        %s
    };

    function automatic logic [CHK_W-1:0] h_col(input int j);
        return H_COL_FLAT[CHK_W*j +: CHK_W];
    endfunction

    function automatic logic [DATA_W-1:0] row_mask(input int i);
        return ROW_MASK_FLAT[DATA_W*i +: DATA_W];
    endfunction
endpackage
""" % (cols, masks)
    wpath("rtl/ecc/ecc_pkg.sv", t)

# ============================================================== encoder netlists
def depth_combine(terms, level, newname, nets):
    """Combine terms with 2-input XORs, always pairing the two shallowest (minimum depth)."""
    terms = sorted(terms, key=lambda t: (level[t], t))
    while len(terms) > 1:
        a, b = terms.pop(0), terms.pop(0)
        n = newname()
        nets.append((n, a, b))
        level[n] = max(level[a], level[b]) + 1
        terms.append(n)
        terms.sort(key=lambda t: (level[t], t))
    return terms[0]

def dname(j): return "d[%d]" % j

def enc_flat():
    lines, xors, depth = [], 0, 0
    for i in range(R):
        lines.append("    assign c[%d] = %s;" % (i, " ^ ".join(dname(j) for j in ROWS[i])))
        xors += len(ROWS[i]) - 1
        depth = max(depth, len(ROWS[i]) - 1)          # as written (a chain); synthesis rebalances
    return lines, [], xors, depth

def enc_tree():
    nets, level, outs, cnt = [], {}, [], [0]
    for j in range(K): level[dname(j)] = 0
    def newname():
        cnt[0] += 1; return "x%d" % cnt[0]
    for i in range(R):
        outs.append(depth_combine([dname(j) for j in ROWS[i]], level, newname, nets))
    depth = max(level[o] for o in outs)
    lines = ["    assign c[%d] = %s;" % (i, outs[i]) for i in range(R)]
    return lines, nets, len(nets), depth

def enc_cse():
    rows = [set(dname(j) for j in ROWS[i]) for i in range(R)]
    nets, level, cnt = [], {}, [0]
    for j in range(K): level[dname(j)] = 0
    def newname():
        cnt[0] += 1; return "t%d" % cnt[0]
    # greedy: extract the pair shared by the most rows, prefer shallow pairs
    while True:
        freq = {}
        for r in rows:
            for p in combinations(sorted(r), 2):
                freq[p] = freq.get(p, 0) + 1
        best = [p for p, f in freq.items() if f >= 2]
        if not best: break
        best.sort(key=lambda p: (-freq[p], max(level[p[0]], level[p[1]]), p))
        a, b = best[0]
        n = newname()
        nets.append((n, a, b)); level[n] = max(level[a], level[b]) + 1
        for r in rows:
            if a in r and b in r:
                r.discard(a); r.discard(b); r.add(n)
    outs = [depth_combine(list(r), level, newname, nets) for r in rows]
    depth = max(level[o] for o in outs)
    lines = ["    assign c[%d] = %s;" % (i, outs[i]) for i in range(R)]
    return lines, nets, len(nets), depth

def emit_enc(name, impl, desc, lines, nets, xors, depth):
    body = []
    if nets:
        body.append("    `ECC_KEEP_ATTR logic %s;" % ", ".join(n for n, _, _ in nets))
        for n, a, b in nets:
            body.append("    assign %s = %s ^ %s;" % (n, a, b))
    body += lines
    t = HDR + KEEP + """// Encoder check-bit network, IMPL %d: %s
// 2-input XOR gates: %d   logic depth: %d
// Define ECC_KEEP to keep this structure through synthesis.
module %s (
    input  logic [31:0] d,
    output logic  [6:0] c
);
%s
endmodule
""" % (impl, desc, xors, depth, name, "\n".join(body))
    wpath("rtl/ecc/%s.sv" % name, t)

# ============================================================== correction logic
def corr_cmp():
    body = ["    assign flip[%d] = (syn == 7'b%s);" % (j, format(H[j], "07b")) for j in range(N)]
    t = HDR + """// Correction logic, comparator form (decoder IMPL 1 and 2).
// flip[j] = 1 when the syndrome equals column j of H (single error at bit j).
module ecc_corr_cmp (
    input  logic  [6:0] syn,
    output logic [38:0] flip,
    output logic        ce
);
%s
    assign ce = |flip;
endmodule
""" % "\n".join(body)
    wpath("rtl/ecc/ecc_corr_cmp.sv", t)
    return 7 * N   # literal count (39 seven-input ANDs)

def corr_espresso():
    from pyeda.inter import exprvars, truthtable, espresso_tts
    s = exprvars("s", R)
    colset = {H[j]: j for j in range(N)}
    odd = lambda x: bin(x).count("1") % 2 == 1
    # flip_j : 1 on column j, 0 on the other 38 columns, don't-care on every other syndrome.
    #          Safe because the result is gated by ce, which is exact.
    # ce_odd : 1 on the 39 columns, 0 on the 25 unused odd syndromes, don't-care on even
    #          syndromes. Safe because ce = (^syn) & ce_odd.
    spec = []
    for j in range(N):
        spec.append("".join("1" if x == H[j] else ("0" if x in colset else "-") for x in range(1 << R)))
    spec.append("".join(("1" if x in colset else "0") if odd(x) else "-" for x in range(1 << R)))
    # single-output minimisation (like `espresso -Dso`): sharing product terms between
    # outputs would make ESPRESSO keep full 7-literal minterms.
    fs = [espresso_tts(truthtable(s, sp))[0] for sp in spec]

    def cubes(f):
        name = type(f).__name__
        if name in ("Variable", "Complement", "AndOp"): return [f]
        if name == "OrOp": return list(f.xs)
        if name in ("_Zero", "Zero"): return []
        raise ValueError(name)
    def lits(cube):
        return list(cube.xs) if type(cube).__name__ == "AndOp" else [cube]
    def idx(l): return int(str(l).split("[")[1].rstrip("]"))
    def vlog(cube):
        return "(" + " & ".join(("~" if str(l).startswith("~") else "") + "syn[%d]" % idx(l)
                                for l in lits(cube)) + ")"
    def pla_cube(cube):
        c = ["-"] * R
        for l in lits(cube): c[idx(l)] = "0" if str(l).startswith("~") else "1"
        return "".join(c)

    names = ["f%d" % j for j in range(N)] + ["ce_odd"]
    pla = ["# GENERATED by model/gen.py - ESPRESSO input. Minimise single-output: espresso -Dso",
           ".i %d" % R, ".o %d" % (N + 1),
           ".ilb " + " ".join("s%d" % i for i in range(R)), ".ob " + " ".join(names),
           ".type fdr", ".p %d" % (1 << R)]
    for x in range(1 << R):
        pla.append("".join(str((x >> i) & 1) for i in range(R)) + " " + "".join(sp[x] for sp in spec))
    pla.append(".e")
    wpath("model/decoder.pla", "\n".join(pla) + "\n")

    mlines, body, nlit = [], [], 0
    for o, f in enumerate(fs):
        cs = cubes(f)
        for cb in cs:
            outv = ["0"] * (N + 1); outv[o] = "1"
            mlines.append(pla_cube(cb) + " " + "".join(outv))
            nlit += len(lits(cb))
        expr = " | ".join(vlog(cb) for cb in cs) if cs else "1'b0"
        tgt = "flip_raw[%d]" % o if o < N else "ce_odd"
        body.append("    assign %s = %s;" % (tgt, expr))
    wpath("model/decoder_min.pla",
          "# GENERATED by model/gen.py - ESPRESSO result (single-output)\n.i %d\n.o %d\n.ob %s\n.p %d\n%s\n.e\n"
          % (R, N + 1, " ".join(names), len(mlines), "\n".join(mlines)))
    t = HDR + """// Correction logic minimised by ESPRESSO (decoder IMPL 3).
//   flip_raw[j]: must be right only on the 39 column syndromes (don't-care elsewhere)
//   ce_odd     : must be right only on odd-weight syndromes (don't-care on even ones)
//   ce   = (^syn) & ce_odd      exact: 1 iff the syndrome equals a column of H
//   flip = flip_raw & ce        so no bit is ever flipped on an uncorrectable syndrome
// SOP literal count: %d (comparator form: %d for the flips, ce = OR of them)
module ecc_corr_espresso (
    input  logic  [6:0] syn,
    output logic [38:0] flip,
    output logic        ce
);
    logic [38:0] flip_raw;
    logic        ce_odd;
%s
    assign ce   = (^syn) & ce_odd;
    assign flip = flip_raw & {39{ce}};
endmodule
""" % (nlit, 7 * N, "\n".join(body))
    wpath("rtl/ecc/ecc_corr_espresso.sv", t)
    # sanity: the gated logic equals the reference on all 128 syndromes
    for x in range(1 << R):
        pt = {s[i]: (x >> i) & 1 for i in range(R)}
        ce = int(fs[N].restrict(pt)) & int(odd(x))
        assert ce == (1 if x in colset else 0), x
        for j in range(N):
            assert (int(fs[j].restrict(pt)) & ce) == (1 if x == H[j] else 0), (x, j)
    return nlit

# ============================================================== vectors
def gen_vectors():
    # One vector per line, 168 bits = 42 hex digits:
    #   [166:128] error mask injected into the stored codeword      (39 bits)
    #   [127:89]  cw_in   = encode(data) XOR mask  = what the RAM returns   (39 bits)
    #   [88:57]   expected data_out        (32)
    #   [56:18]   expected cw_out          (39)
    #   [17:11]   expected syndrome        (7)
    #   [10] expected ce   [9] expected ue   [8:3] expected err_pos   [2:0] unused (0)
    # The original data word is recovered as (cw_in XOR mask)[31:0].
    vec = []
    def add(orig, mask):
        cw = inject(orig, mask)
        d, co, s, ce, ue, pos = decode(cw)
        v = ((mask << 128) | (cw << 89) | (d << 57) | (co << 18) | (s << 11)
             | (ce << 10) | (ue << 9) | (pos << 3))
        vec.append("%042x" % v)
    words = test_words(10)
    for d in words:
        cw = encode(d)
        add(cw, 0)
        for j in range(N): add(cw, 1 << j)
        for a, b in combinations(range(N), 2): add(cw, (1 << a) | (1 << b))
    # all triple errors on two words: decoders must behave exactly like the model
    for d in (0x00000000, 0x89ABCDEF):
        cw = encode(d)
        for a, b, c in combinations(range(N), 3): add(cw, (1 << a) | (1 << b) | (1 << c))
    wpath("tb/vectors/ecc_vectors.hex", "\n".join(vec) + "\n")
    return len(vec), len(words)

# ============================================================== main
if __name__ == "__main__":
    vectors_only = "--vectors-only" in sys.argv
    print("P12 codec generator" + (" (vectors only)" if vectors_only else ""))
    hsiao.self_test(verbose=False)
    if vectors_only:
        nvec, nwords = gen_vectors()
        print("%d vectors from %d data words" % (nvec, nwords))
        sys.exit(0)
    gen_pkg()
    metrics = []
    for name, impl, desc, fn in (("ecc_enc_flat", 1, "flat XOR expression per row", enc_flat),
                                 ("ecc_enc_cse", 2, "common sub-expression elimination", enc_cse),
                                 ("ecc_enc_tree", 3, "balanced 2-input XOR tree per row", enc_tree)):
        lines, nets, xors, depth = fn()
        emit_enc(name, impl, desc, lines, nets, xors, depth)
        metrics.append((impl, desc, xors, depth))
    cmp_lits = corr_cmp()
    esp_lits = corr_espresso()
    nvec, nwords = gen_vectors()
    mis, det = hsiao.self_test(verbose=False)

    md = ["# Hand metrics (generated by model/gen.py)", "",
          "Syndrome = encoder network on the received data, XOR the received check bits (+1 XOR level).", "",
          "| Encoder IMPL | Structure | 2-input XORs | Logic depth |", "| --- | --- | --- | --- |",
          "| 0 | behavioural reduction (synthesis decides) | 89 before sharing | - |"]
    for impl, desc, x, dpt in metrics:
        md.append("| %d | %s | %d | %d |" % (impl, desc, x, dpt))
    md += ["", "| Correction logic | Literals | Notes |", "| --- | --- | --- |",
           "| comparators (dec IMPL 0-2) | %d | 39 seven-input ANDs, ce = OR of them (+273 literals if ce were its own SOP) |" % cmp_lits,
           "| ESPRESSO (dec IMPL 3) | %d | flips and ce_odd minimised single-output with don't-cares; ce = parity & ce_odd |" % esp_lits,
           "", "Test vectors: %d (%d data words x (1 clean + 39 single + 741 double) + 2 x 9139 triples)." % (nvec, nwords),
           "Triple errors: %d miscorrected, %d flagged uncorrectable (no guarantee beyond 2 errors)." % (mis, det)]
    wpath("reports/ecc_hand_metrics.md", "\n".join(md) + "\n")
    print("\n".join(md))
